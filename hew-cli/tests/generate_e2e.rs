mod support;

use std::path::Path;

fn command(root: &Path, args: &[&str], success: bool) -> String {
    let output = support::run_hew_in(root, args);
    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
    assert_eq!(
        output.status.success(),
        success,
        "{args:?}: {stdout}\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
    stdout
}

#[test]
fn generation_tracks_package_inputs_and_preserves_checked_output() {
    support::require_codegen();
    let project = support::tempdir();
    let root = project.path();
    std::fs::create_dir(root.join("tools")).unwrap();
    std::fs::write(
        root.join("hew.toml"),
        r#"
[package]
name = "generated_example"
version = "0.1.0"
[[generate]]
name = "value"
run = "tools/generate.hew"
inputs = ["input.txt"]
outputs = "out"
[[generate]]
name = "extra"
run = "tools/extra.hew"
outputs = "extra"
"#,
    )
    .unwrap();
    std::fs::write(root.join("input.txt"), "4").unwrap();
    std::fs::write(root.join("template.txt"), "2").unwrap();
    std::fs::write(root.join("tools/extra.hew"), "import std.fs;\nfn main() { fs.write(\"extra/other.hew\", \"// @generated by hew generate (extra) from ; do not edit\\npub fn other() {}\\n\").expect(\"output\"); }\n").unwrap();
    std::fs::write(root.join("tools/generate.hew"), r#"
import std.fs;
fn main() {
    let value = fs.read("input.txt").expect("declared input") + fs.read("template.txt").expect("own package input");
    let source = "// @generated by hew generate (value) from input.txt; do not edit\npub fn answer() -> i64 { " + value + " }\n";
    fs.write("out/value.hew", source).expect("output");
    match fs.write("escape.hew", source) {
        .Err(.PermissionDenied) => {}
        _ => panic("generator write escaped its output directory"),
    }
}
"#).unwrap();
    std::fs::write(
        root.join("main.hew"),
        "import out.value;\nfn main() { println(value.answer()); }\n",
    )
    .unwrap();
    assert_eq!(command(root, &["run"], true).trim(), "42");
    let output = root.join("out/value.hew");
    let original = std::fs::read(&output).unwrap();
    let modified = output.metadata().unwrap().modified().unwrap();
    command(root, &["generate"], true);
    assert_eq!(output.metadata().unwrap().modified().unwrap(), modified);
    assert!(!root.join("escape.hew").exists());
    std::fs::write(root.join("template.txt"), "3").unwrap();
    command(root, &["generate", "--check"], false);
    assert_eq!(std::fs::read(&output).unwrap(), original);
    assert_eq!(command(root, &["run"], true).trim(), "43");
    command(root, &["generate", "--check"], true);
    let original = std::fs::read(&output).unwrap();
    command(root, &["fmt", "out/value.hew"], true);
    assert_eq!(std::fs::read(&output).unwrap(), original);
}
