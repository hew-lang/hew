//! Export the native character operations for the sandbox VM.
use std::fmt::Write as _;
use std::path::PathBuf;

use hew_runtime::string::{
    hew_char_is_alphanumeric, hew_char_is_ascii, hew_char_is_control, hew_char_is_digit,
    hew_char_is_letter, hew_char_is_lower, hew_char_is_punctuation, hew_char_is_upper,
    hew_char_is_whitespace, hew_char_to_lower, hew_char_to_title, hew_char_to_upper,
};

fn properties(value: char) -> u16 {
    let cp = value as i32;
    // SAFETY: `value` is a Unicode scalar; these operations retain no state.
    let flags = unsafe {
        [
            hew_char_is_digit(cp),
            hew_char_is_letter(cp),
            hew_char_is_alphanumeric(cp),
            hew_char_is_whitespace(cp),
            hew_char_is_upper(cp),
            hew_char_is_lower(cp),
            hew_char_is_punctuation(cp),
            hew_char_is_control(u32::from(value)),
            hew_char_is_ascii(u32::from(value)),
        ]
    };
    flags
        .iter()
        .enumerate()
        .fold(0, |bits, (index, flag)| bits | (u16::from(*flag) << index))
}

fn table(output: &mut String, name: &str, values: &[u32], stride: usize) {
    writeln!(
        output,
        "// prettier-ignore\nexport const {name}: readonly number[] = ["
    )
    .unwrap();
    for row in values.chunks(stride * 4) {
        output.push_str("  ");
        for (index, value) in row.iter().enumerate() {
            if index > 0 {
                output.push(' ');
            }
            write!(output, "{value},").unwrap();
        }
        output.push('\n');
    }
    output.push_str("];\n\n");
}

fn generate() -> String {
    let mut categories = Vec::new();
    let mut mappings = [Vec::new(), Vec::new(), Vec::new()];
    let mut start = 0;
    let mut previous = 0;
    for cp in 0..=0x0011_0000 {
        let value = char::from_u32(cp);
        let current = value.map_or(0, properties);
        if current != previous {
            if previous != 0 {
                categories.extend([start, cp - 1, u32::from(previous)]);
            }
            start = cp;
            previous = current;
        }
        if let Some(value) = value {
            let scalar = value as i32;
            // SAFETY: each input is a Unicode scalar and the mappings retain no state.
            let mapped = unsafe {
                [
                    hew_char_to_upper(scalar),
                    hew_char_to_lower(scalar),
                    hew_char_to_title(scalar),
                ]
            };
            for (table, mapped) in mappings.iter_mut().zip(mapped) {
                let mapped = u32::try_from(mapped).expect("case mapping is a Unicode scalar");
                if mapped != cp {
                    table.extend([cp, mapped]);
                }
            }
        }
    }
    let version = char::UNICODE_VERSION;
    let mut output = format!(
        "// Generated by make unicode-tables from Hew's native character operations.\n\
         // Rust Unicode {}.{}.{}; punctuation uses the runtime's pinned finl_unicode tables.\n\n",
        version.0, version.1, version.2
    );
    table(&mut output, "CATEGORY_RANGES", &categories, 3);
    for (name, values) in ["UPPER_MAPPING", "LOWER_MAPPING", "TITLE_MAPPING"]
        .into_iter()
        .zip(mappings)
    {
        table(&mut output, name, &values, 2);
    }
    output.truncate(output.trim_end().len());
    output.push('\n');
    output
}

fn main() {
    let mut arguments = std::env::args_os().skip(1);
    let first = arguments.next().expect("unicode_tables [--check] OUTPUT");
    let check = first == "--check";
    let path = PathBuf::from(if check {
        arguments.next().expect("missing output path")
    } else {
        first
    });
    assert!(arguments.next().is_none(), "unexpected arguments");
    let output = generate();
    if check {
        assert_eq!(
            std::fs::read_to_string(path).expect("read Unicode tables"),
            output,
            "run make unicode-tables"
        );
    } else {
        std::fs::write(path, output).expect("write Unicode tables");
    }
}
