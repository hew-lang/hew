//! Optional presentation settings for generated documentation sites.

use std::path::Path;

use serde::Deserialize;

/// A link in the generated site's primary navigation.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NavLink {
    pub label: String,
    pub url: String,
}

/// A guide link as it appears in the documentation index.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct GuideEntry {
    pub module: String,
    pub label: String,
    pub summary: String,
}

/// A reader-oriented group of guides in the documentation index.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct GuideGroup {
    pub title: String,
    pub guides: Vec<GuideEntry>,
}

/// Presentation and collection settings for `hew doc` HTML and Markdown output.
///
/// The defaults produce a self-contained package reference. Projects can pass
/// `--site-config` to name and arrange a published site without baking that
/// site's branding into the generator.
#[derive(Debug, Clone, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct DocSiteConfig {
    #[serde(skip, default = "generator_version")]
    pub display_version: String,
    pub site_title: String,
    pub brand: String,
    pub brand_tag: String,
    pub index_title: String,
    pub index_description: String,
    pub guide_title: String,
    pub guide_description: String,
    pub guide_start: Option<String>,
    pub guide_groups: Vec<GuideGroup>,
    pub module_title: String,
    pub module_description: String,
    pub module_filter: bool,
    pub guide_order: Vec<String>,
    pub exclude_modules: Vec<String>,
    pub nav_links: Vec<NavLink>,
    pub footer_text: String,
    pub footer_link_label: Option<String>,
    pub footer_link_url: Option<String>,
}

impl Default for DocSiteConfig {
    fn default() -> Self {
        Self {
            display_version: generator_version(),
            site_title: "Documentation".to_string(),
            brand: "Documentation".to_string(),
            brand_tag: "Generated by hew doc {version}".to_string(),
            index_title: "Documentation".to_string(),
            index_description: "Generated module and API documentation.".to_string(),
            guide_title: "Guides".to_string(),
            guide_description: "Conceptual and task-oriented documentation.".to_string(),
            guide_start: None,
            guide_groups: Vec::new(),
            module_title: "Modules".to_string(),
            module_description: "Public declarations and methods by module.".to_string(),
            module_filter: true,
            guide_order: Vec::new(),
            exclude_modules: Vec::new(),
            nav_links: Vec::new(),
            footer_text: "Generated by hew doc with Hew {version}".to_string(),
            footer_link_label: None,
            footer_link_url: None,
        }
    }
}

impl DocSiteConfig {
    pub fn load(path: &Path) -> Result<Self, String> {
        let source = std::fs::read_to_string(path)
            .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
        toml::from_str(&source).map_err(|error| {
            format!(
                "invalid documentation site config {}: {error}",
                path.display()
            )
        })
    }

    #[must_use]
    pub fn includes(&self, module_name: &str) -> bool {
        !self.exclude_modules.iter().any(|name| name == module_name)
    }

    #[must_use]
    pub fn guide_rank(&self, module_name: &str) -> usize {
        if let Some(position) = self
            .guide_groups
            .iter()
            .flat_map(|group| &group.guides)
            .position(|guide| guide.module == module_name)
        {
            return position;
        }
        self.guide_order
            .iter()
            .position(|name| name == module_name)
            .unwrap_or(self.guide_order.len())
    }

    #[must_use]
    pub fn is_guide(&self, module_name: &str) -> bool {
        self.guide_groups
            .iter()
            .flat_map(|group| &group.guides)
            .any(|guide| guide.module == module_name)
            || self.guide_order.iter().any(|name| name == module_name)
    }

    #[must_use]
    pub fn guide_entry(&self, module_name: &str) -> Option<&GuideEntry> {
        self.guide_groups
            .iter()
            .flat_map(|group| &group.guides)
            .find(|guide| guide.module == module_name)
    }

    #[must_use]
    pub fn expand_version(&self, text: &str) -> String {
        text.replace("{version}", &self.display_version)
    }
}

fn generator_version() -> String {
    env!("CARGO_PKG_VERSION").to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn defaults_are_project_neutral() {
        let config = DocSiteConfig::default();
        assert_eq!(config.site_title, "Documentation");
        assert!(config.nav_links.is_empty());
        assert!(config.exclude_modules.is_empty());
        assert!(config.guide_groups.is_empty());
    }

    #[test]
    fn parses_site_overrides() {
        let config: DocSiteConfig = toml::from_str(
            r#"
site_title = "Example API"
exclude_modules = ["internal::fixture"]

[[guide_groups]]
title = "Start here"
guides = [
  { module = "guide::start", label = "Start", summary = "Begin using the project." },
]

[[nav_links]]
label = "Project"
url = "https://example.com"
"#,
        )
        .expect("config parses");
        assert_eq!(config.site_title, "Example API");
        assert_eq!(config.guide_rank("guide::start"), 0);
        assert_eq!(config.guide_entry("guide::start").unwrap().label, "Start");
        assert!(config.is_guide("guide::start"));
        assert!(!config.includes("internal::fixture"));
        assert_eq!(config.nav_links[0].label, "Project");
        assert_eq!(config.display_version, env!("CARGO_PKG_VERSION"));
    }

    #[test]
    fn expands_an_explicit_site_version() {
        let config = DocSiteConfig {
            display_version: "1.2.3".to_string(),
            ..DocSiteConfig::default()
        };
        assert_eq!(config.expand_version("Hew {version}"), "Hew 1.2.3");
    }
}
