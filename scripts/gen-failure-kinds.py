# Kinds a crash can carry that have no trap code of their own.
UNCODED_KINDS = [
    ("Signal", "A hardware signal the runtime does not classify further."),
    ("UnknownFault", "A code that names no failure kind."),
    ("Cancelled", "Cooperative cancellation reported as a failure."),
    ("Deadline", "A deadline that elapsed and was reported as a failure."),
]

# Metrics derived from the kind list.
CRASH_SERIES = "actors_crashes_total"
CRASH_LABEL_KEYS = ["trap_kind", "actor_type"]
GIVEUP_SERIES = "supervisor_giveups_total"


def render() -> str:
    out = []
    w = out.append
    w(
        "// @generated by scripts/gen-failure-kinds.py; edit the table there, not this file.\n"
    )
    w("//! The failure kinds the runtime reports, and the metrics derived from them.\n")
    w("\n")
    w("use std::ffi::CStr;\n")
    w("\n")
    for code, suffix, _name, doc in KINDS:
        w(f"/// {doc}\n")
        w(f"pub const HEW_TRAP_{suffix}: i32 = {code};\n")
    w("\n")
    w("/// Every coded failure kind: `(code, name)`, in code order.\n")
    w("pub const FAILURE_KINDS: &[(i32, &str)] = &[\n")
    for code, _suffix, name, _doc in KINDS:
        w(f'    ({code}, "{name}"),\n')
    w("];\n\n")
    w("/// Declaration-order tag of a public `TrapKind`, when known.\n")
    w("#[must_use]\npub const fn trap_kind_tag(code: i32) -> Option<u32> {\n    match code {\n")
    for tag, (code, _suffix, _name, _doc) in enumerate(KINDS):
        w(f"        {code} => Some({tag}),\n")
    w("        _ => None,\n    }\n}\n\n")
    for name, doc in UNCODED_KINDS:
        w(f"/// {doc}\n")
        w(f'pub const KIND_{name.upper()}: &str = "{name}";\n')
    w("\n")
    w("/// The NUL-terminated name of a coded failure kind, readable from a core.\n")
    w("#[must_use]\n")
    w("pub const fn kind_cstr(code: i32) -> Option<&'static CStr> {\n")
    w("    match code {\n")
    for code, _suffix, name, _doc in KINDS:
        w(f'        {code} => Some(c"{name}"),\n')
    w("        _ => None,\n")
    w("    }\n")
    w("}\n\n")
    for name, _doc in UNCODED_KINDS:
        w(f"/// NUL-terminated [`KIND_{name.upper()}`].\n")
        w(f'pub const KIND_{name.upper()}_CSTR: &CStr = c"{name}";\n')
    w("\n")
    w("/// Every value the `trap_kind` label of the crash counter can take.\n")
    w("pub const TRAP_KIND_LABEL_VALUES: &[&str] = &[\n")
    for _code, _suffix, name, _doc in KINDS:
        w(f'    "{name}",\n')
    for name, _doc in UNCODED_KINDS:
        w(f'    "{name}",\n')
    w("];\n\n")
    w("/// Prometheus series counting actor crashes by kind and actor type.\n")
    w(f'pub const CRASH_SERIES: &str = "{CRASH_SERIES}";\n')
    w("/// Label keys of [`CRASH_SERIES`], in rendering order.\n")
    keys = ", ".join(f'"{key}"' for key in CRASH_LABEL_KEYS)
    w(f"pub const CRASH_LABEL_KEYS: [&str; {len(CRASH_LABEL_KEYS)}] = [{keys}];\n")
    w("/// Prometheus series counting supervisors that gave up on a child.\n")
    w(f'pub const GIVEUP_SERIES: &str = "{GIVEUP_SERIES}";\n')
    return "".join(out)


def render_failure_source(source: str) -> str:
    before, rest = source.split(TRAP_BEGIN, 1)
    _, after = rest.split(TRAP_END, 1)
    variants = "".join(f"    /// {doc}\n    {name};\n" for _, _, name, doc in KINDS)
    return before + TRAP_BEGIN + "/// A known runtime failure.\npub enum TrapKind {\n" + variants + "}\n" + TRAP_END + after


def main() -> int:
    text = render()
    source = FAILURE_SOURCE.read_text(encoding="utf-8")
    failure_text = render_failure_source(source)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(ROOT)} is stale; run scripts/gen-failure-kinds.py",
                file=sys.stderr,
            )
            return 1
        if source != failure_text:
            print(f"{FAILURE_SOURCE.relative_to(ROOT)} is stale; run scripts/gen-failure-kinds.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    FAILURE_SOURCE.write_text(failure_text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
