import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(root, "..");
const fixturesRoot = path.join(root, "fixtures");
const deferred = readDeferredManifest();
const workspaceVersion = readWorkspaceVersion();

test("sandbox VM package tracks the workspace and recorded fixtures retain release versions", () => {
  const packageVersion = readJson(path.join(root, "package.json")).version;
  assert.equal(packageVersion, workspaceVersion);

  for (const fixture of fs.readdirSync(fixturesRoot, { withFileTypes: true })) {
    if (!fixture.isDirectory()) continue;
    const bytecodePath = path.join(fixturesRoot, fixture.name, "bytecode.json");
    if (!fs.existsSync(bytecodePath)) continue;
    assert.match(
      readJson(bytecodePath).hew_version,
      /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/,
      `${fixture.name} must retain its recorded Hew release version`,
    );
  }
});

test("fixture bytecode provenance is compiled or explicitly deferred", () => {
  const fixtureDirs = fs
    .readdirSync(fixturesRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const fixtureSet = new Set(fixtureDirs);

  for (const fixture of deferred.keys()) {
    assert.ok(
      fixtureSet.has(fixture),
      `deferred fixture ${fixture} does not exist`,
    );
  }

  for (const fixture of fixtureDirs) {
    const bytecodePath = path.join(fixturesRoot, fixture, "bytecode.json");
    if (!fs.existsSync(bytecodePath)) {
      continue;
    }

    const bytecode = readJson(bytecodePath);
    const deferredEntry = deferred.get(fixture);
    assert.equal(
      typeof bytecode.compiler_version,
      "string",
      `${fixture} compiler_version must be a string`,
    );
    assert.ok(
      !bytecode.compiler_version.includes("m2-fixture"),
      `${fixture} still uses the M2 fixture marker`,
    );
    assert.ok(
      !bytecode.compiler_version.includes("m4-fixture"),
      `${fixture} still uses the M4 fixture marker`,
    );
    assert.ok(
      !bytecode.compiler_version.includes("m6-fixture"),
      `${fixture} still uses the M6 fixture marker`,
    );

    if (deferredEntry) {
      assert.equal(
        bytecode.compiler_version,
        deferredEntry.compiler_version,
        `${fixture} deferred marker must match fixtures/README.md`,
      );
    } else {
      assert.equal(
        bytecode.compiler_version,
        `hew-wasm-${bytecode.hew_version}`,
        `${fixture} must be generated by the canonical sandbox compiler`,
      );
    }
  }
});

test("sandbox fixture check rejects a source that no longer compiles", () => {
  const tempDir = fs.mkdtempSync(
    path.join(os.tmpdir(), "hew-sandbox-fixtures-"),
  );
  const tempFixtures = path.join(tempDir, "fixtures");
  fs.cpSync(fixturesRoot, tempFixtures, { recursive: true });

  try {
    fs.writeFileSync(
      path.join(tempFixtures, "01-hello-world", "main.hew"),
      'fn main() { let value: i64 = "wrong type"; }\n',
    );

    const result = spawnSync("make", ["sandbox-fixtures-check"], {
      cwd: repoRoot,
      env: { ...process.env, HEW_SANDBOX_FIXTURES_DIR: tempFixtures },
      encoding: "utf8",
    });

    assert.notEqual(
      result.status,
      0,
      "sandbox-fixtures-check should fail after a source type error",
    );
    assert.match(
      result.stderr + result.stdout,
      /compiler produced diagnostics.*type mismatch/i,
    );
  } finally {
    fs.rmSync(tempDir, { recursive: true, force: true });
  }
});

function readDeferredManifest() {
  const readme = fs.readFileSync(path.join(fixturesRoot, "README.md"), "utf8");
  const match = readme.match(
    /```json sandbox-fixtures-deferred\n([\s\S]*?)\n```/,
  );
  assert.ok(
    match,
    "fixtures/README.md must contain sandbox-fixtures-deferred JSON block",
  );
  const parsed = JSON.parse(match[1]);
  const entries = new Map();
  for (const entry of parsed.deferred) {
    assert.equal(typeof entry.fixture, "string");
    assert.equal(typeof entry.feature, "string");
    assert.equal(typeof entry.reason, "string");
    if (entry.compiler_version !== undefined) {
      assert.match(entry.compiler_version, /^handcrafted-pending-/);
    }
    assert.ok(
      !entries.has(entry.fixture),
      `duplicate deferred fixture ${entry.fixture}`,
    );
    entries.set(entry.fixture, entry);
  }
  return entries;
}

function readWorkspaceVersion() {
  const cargoToml = fs.readFileSync(path.join(repoRoot, "Cargo.toml"), "utf8");
  const match = cargoToml.match(
    /\[workspace\.package\][\s\S]*?\nversion\s*=\s*"([^"]+)"/,
  );
  assert.ok(match, "workspace package version must be declared");
  return match[1];
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}
