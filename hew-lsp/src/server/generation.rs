//! Read-only generation diagnostics. Only an explicit command runs a generator.

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use tower_lsp_server::ls_types::{Diagnostic, DiagnosticSeverity, NumberOrString};

pub(super) fn diagnostics(path: &Path) -> Vec<Diagnostic> {
    let Some(root) = path.parent().and_then(hew_pkg::project::find_package_root) else {
        return Vec::new();
    };
    let Ok(manifest) = hew_pkg::manifest::parse_manifest(&root.join("hew.toml")) else {
        return Vec::new();
    };
    let mut diagnostics = Vec::new();
    for step in &manifest.generate {
        if path.starts_with(root.join(&step.outputs)) {
            diagnostics.push(Diagnostic {
                severity: Some(DiagnosticSeverity::WARNING),
                code: Some(NumberOrString::String("W_GENERATED_SOURCE".into())),
                source: Some("hew".into()),
                message: format!("generated by `{}` from {}; edit its generator or inputs, because regeneration replaces this file", step.name, step.inputs.join(", ")),
                ..Diagnostic::default()
            });
        }
        if hew_pkg::generate::is_stale(&root, step, hew_compile::VERSION).unwrap_or(true) {
            diagnostics.push(Diagnostic {
                severity: Some(DiagnosticSeverity::WARNING),
                code: Some(NumberOrString::String("W_GENERATE_STALE".into())),
                source: Some("hew".into()),
                message: format!(
                    "generated output is stale for `{}`; run `hew generate`",
                    step.name
                ),
                data: Some(serde_json::json!({ "generateRoot": root })),
                ..Diagnostic::default()
            });
        }
    }
    diagnostics
}

pub(super) fn affected_by(path: &Path, changed: &HashSet<PathBuf>) -> bool {
    let Some(root) = path.parent().and_then(hew_pkg::project::find_package_root) else {
        return false;
    };
    let Ok(manifest) = hew_pkg::manifest::parse_manifest(&root.join("hew.toml")) else {
        return false;
    };
    if manifest.generate.is_empty() {
        return false;
    }
    if changed
        .iter()
        .any(|path| hew_pkg::generate::is_package_path(&root, path))
    {
        return true;
    }
    for step in &manifest.generate {
        if hew_pkg::generate::generator_entry(&root, &manifest, step).is_ok_and(
            |(_, own_package)| {
                changed
                    .iter()
                    .any(|path| hew_pkg::generate::is_package_path(&own_package, path))
            },
        ) {
            return true;
        }
        let stamp_path = root
            .join(".hew/generate")
            .join(format!("{}.stamp", step.name));
        if std::fs::read(stamp_path)
            .ok()
            .and_then(|bytes| serde_json::from_slice::<hew_pkg::generate::Stamp>(&bytes).ok())
            .is_some_and(|stamp| changed.iter().any(|path| stamp.sources.contains_key(path)))
        {
            return true;
        }
    }
    false
}
