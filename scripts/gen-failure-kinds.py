#!/usr/bin/env python3
"""Generate the runtime's failure-kind list.

This table is the one source for every failure kind the runtime reports: the
trap codes codegen stamps, the names in `hew: failure:` lines, the `trap_kind`
label values of `actors_crashes_total` and the supervisor give-up counter. Edit
the table here, then run this script; `--check` fails when the generated file
is stale.

    python3 scripts/gen-failure-kinds.py          # rewrite the generated file
    python3 scripts/gen-failure-kinds.py --check  # verify it is current
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "hew-runtime" / "src" / "failure_kinds.rs"
FAILURE_SOURCE = ROOT / "std" / "failure.hew"
TRAP_BEGIN = "// BEGIN GENERATED TRAP KINDS\n"
TRAP_END = "// END GENERATED TRAP KINDS\n"

